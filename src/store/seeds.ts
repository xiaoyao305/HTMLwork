function birthdayAgo(years: number, months: number): string {
  const d = new Date();
  d.setMonth(d.getMonth() - (years * 12 + months));
  return toDateStr(d);
}

function atTime(date: string, time: string): string {
  return `${date}T${time}:00`;
}

